/**
 * Generates contracts/test/vectors/textile-venue.json with the FROZEN TS codec (packages/shared/src/textile-venue.ts),
 * so the Solidity decoder of CobraRouterV2 is checked byte for byte against it (test/V2Vectors.t.sol).
 *   pnpm exec tsx contracts/script/gen-textile-vector.ts
 * Order bytes are real abi.encode(LimitOrder) values (UniswapX layout); signatures are dummy 65-byte blobs (the codec
 * does not interpret them). Addresses are Celo mainnet ones; nothing here touches the network.
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { encodeAbiParameters, keccak256, type Hex } from "viem";
import { decodeTextileVenue, encodeTextileVenue, isTextileVenue, TEXTILE_REACTOR_CELO } from "../../packages/shared/src/textile-venue";

const USDT = "0x48065fbBE25f71C9282ddf5e1cD6D6A887483D5e";
const WBRL = "0xD76f5Faf6888e24D9F04Bf92a0c8B921FE4390e0";
const PREFERRED_FILLER_VALIDATION = "0x10B9EbA3a175Df418a35CB8329a527691EE258C5";
const MAKER = "0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC";
const ROUTER_V2 = "0x00000000000000000000000000000000c0b4a002";

const LIMIT_ORDER = [
  {
    type: "tuple",
    components: [
      {
        name: "info",
        type: "tuple",
        components: [
          { name: "reactor", type: "address" },
          { name: "swapper", type: "address" },
          { name: "nonce", type: "uint256" },
          { name: "deadline", type: "uint256" },
          { name: "additionalValidationContract", type: "address" },
          { name: "additionalValidationData", type: "bytes" },
        ],
      },
      {
        name: "input",
        type: "tuple",
        components: [
          { name: "token", type: "address" },
          { name: "amount", type: "uint256" },
          { name: "maxAmount", type: "uint256" },
        ],
      },
      {
        name: "outputs",
        type: "tuple[]",
        components: [
          { name: "token", type: "address" },
          { name: "amount", type: "uint256" },
          { name: "recipient", type: "address" },
        ],
      },
    ],
  },
] as const;

function limitOrder(nonce: bigint, buy: bigint, outs: bigint[], validation: Hex, validationData: Hex): Hex {
  return encodeAbiParameters(LIMIT_ORDER, [
    {
      info: {
        reactor: TEXTILE_REACTOR_CELO,
        swapper: MAKER,
        nonce,
        deadline: 1_800_000_120n,
        additionalValidationContract: validation,
        additionalValidationData: validationData,
      },
      input: { token: WBRL, amount: buy, maxAmount: buy },
      outputs: outs.map((amount) => ({ token: USDT, amount, recipient: MAKER })),
    },
  ]);
}

const exclusive = encodeAbiParameters([{ type: "address[]" }, { type: "uint256" }], [[ROUTER_V2], 1_800_000_120n]);
const orders = [
  { order: limitOrder(1n, 540_000000000000000000n, [100_000000n], "0x0000000000000000000000000000000000000000", "0x"), sig: `0x${"11".repeat(64)}1b` as Hex },
  { order: limitOrder(2n, 27_500000000000000000n, [4_000000n, 1_000000n], PREFERRED_FILLER_VALIDATION, exclusive), sig: `0x${"22".repeat(64)}1c` as Hex },
];
const path = encodeTextileVenue(orders);
if (!isTextileVenue(path)) throw new Error("codec self-check failed");
const back = decodeTextileVenue(path);
if (back.length !== 2 || back[1].order !== orders[1].order || back[0].sig !== orders[0].sig) throw new Error("roundtrip failed");

const out = {
  _comment: "GENERATED by contracts/script/gen-textile-vector.ts from packages/shared/src/textile-venue.ts — do not edit by hand",
  reactor: TEXTILE_REACTOR_CELO,
  tokenIn: USDT,
  tokenOut: WBRL,
  orders,
  path,
  pathHash: keccak256(path),
};
const file = resolve(import.meta.dirname, "../test/vectors/textile-venue.json");
writeFileSync(file, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${file} (${(path.length - 2) / 2} path bytes)`);
