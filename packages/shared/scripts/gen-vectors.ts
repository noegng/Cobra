/**
 * Generates contracts/test/vectors/eip712.json — the cross-language parity fixture.
 * The Solidity router MUST reproduce every hash in this file (see contracts/test/Vectors.t.sol).
 * Run: pnpm vectors
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256, toHex, type Address, type Hex } from "viem";
import {
  CELO_CHAIN_ID,
  PullKind,
  TYPE_STRINGS,
  encodePath,
  hashIntent,
  hashInvoice,
  intentDigest,
  legNonce,
  type OnchainInvoice,
} from "../src/index";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/test/vectors/eip712.json");

const ROUTER = "0x00000000000000000000000000000000c0b4a000" as Address;
const TOKEN_A = "0x000000000000000000000000000000000000a001" as Address; // e.g. USDC
const TOKEN_B = "0x000000000000000000000000000000000000b002" as Address; // e.g. USDT
const TOKEN_OUT = "0x000000000000000000000000000000000000f003" as Address; // e.g. wARS
const PAYER = "0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266" as Address;
const MERCHANT = "0x70997970C51812dc3A010C7d01b50e0d17dc79C8" as Address;

const invoice: OnchainInvoice = {
  id: keccak256(toHex("cobra-test-invoice-1")),
  merchant: MERCHANT,
  tokenOut: TOKEN_OUT,
  amountOut: 4500n * 10n ** 18n,
  deadline: 1_800_000_000n,
};

const cases = [
  { name: "same_token", legs: [{ token: TOKEN_OUT, amountIn: 4500n * 10n ** 18n, kind: PullKind.PERMIT2, path: "0x" as Hex }] },
  {
    name: "one_swap",
    legs: [{ token: TOKEN_A, amountIn: 3_100_000n, kind: PullKind.EIP3009, path: encodePath([TOKEN_A, TOKEN_OUT], [500]) }],
  },
  {
    name: "three_legs_mixed",
    legs: [
      { token: TOKEN_A, amountIn: 1_000_000n, kind: PullKind.EIP3009, path: encodePath([TOKEN_A, TOKEN_B, TOKEN_OUT], [100, 500]) },
      { token: TOKEN_B, amountIn: 2_000_000n, kind: PullKind.PERMIT2, path: encodePath([TOKEN_B, TOKEN_OUT], [500]) },
      { token: TOKEN_OUT, amountIn: 10n ** 18n, kind: PullKind.ALLOWANCE, path: "0x" as Hex },
    ],
  },
];

const vectors = {
  _comment: "GENERATED by packages/shared/scripts/gen-vectors.ts — do not edit by hand",
  chainId: CELO_CHAIN_ID,
  router: ROUTER,
  payer: PAYER,
  typeStrings: TYPE_STRINGS,
  typeHashes: Object.fromEntries(Object.entries(TYPE_STRINGS).map(([k, v]) => [k, keccak256(toHex(v))])),
  invoice: { ...invoice, amountOut: invoice.amountOut.toString(), deadline: invoice.deadline.toString() },
  invoiceHash: hashInvoice(invoice),
  cases: cases.map((c) => {
    const digest = intentDigest(ROUTER, CELO_CHAIN_ID, invoice, PAYER, c.legs);
    return {
      name: c.name,
      legs: c.legs.map((l) => ({ ...l, amountIn: l.amountIn.toString(), pathHash: keccak256(l.path) })),
      intentHash: hashIntent(invoice, PAYER, c.legs),
      intentDigest: digest,
      legNonces: c.legs.map((_, i) => legNonce(digest, i)),
    };
  }),
};

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify(vectors, null, 2) + "\n");
console.log(`wrote ${out}`);
